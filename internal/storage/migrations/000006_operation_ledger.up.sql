-- Operation ledger: one row per intended business mutation, with an explicit
-- state machine that distinguishes "definitely failed" from "may have succeeded".
--
-- Design: docs/audit/reliability-review.md §3.2-§3.3. This closes REL-02 and is
-- the primitive the middleware, the money/inventory tools and the reconciler use
-- instead of inferring outcome from an HTTP status.
--
-- States: pending -> executing -> {succeeded, failed, unknown}
--         unknown -> reconciling -> {succeeded, failed, unknown}
--         failed  -> pending   (explicit retry, only when not-applied is proven)
--
-- Every transition is a conditional UPDATE guarded by the current state and, for
-- anything after pending, by the fencing token issued when the row was claimed.

CREATE TABLE IF NOT EXISTS operations (
    id               uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    -- Caller-supplied or derived (sha256(subject || args_hash)); the replay guard.
    idempotency_key  text        NOT NULL,
    operation        text        NOT NULL,          -- tool name, e.g. magento.invoice.capture
    instance_id      text        NOT NULL REFERENCES datasource_instances(id) ON DELETE RESTRICT,
    subject_hash     bytea       NOT NULL,          -- who asked
    entity_type      text        NOT NULL
                     CHECK (entity_type IN ('order','invoice','creditmemo','shipment','product','stock','category','customer')),
    entity_id        text        NOT NULL,          -- order/invoice id, SKU, ...
    -- Money is integer minor units plus a currency; never a float.
    amount_minor     bigint      NULL,
    currency         text        NULL,
    args_hash        bytea       NOT NULL,          -- sha256(JCS(args)), same hash the confirmation flow uses
    confirmation_id  uuid        NULL,              -- the approval that authorised this mutation
    state            text        NOT NULL DEFAULT 'pending'
                     CHECK (state IN ('pending','executing','succeeded','failed','unknown','reconciling')),
    attempt          integer     NOT NULL DEFAULT 0,
    -- Fencing token for the current attempt. Regenerated by pending->executing and
    -- unknown->reconciling; required by every write that reports an outcome.
    fence            uuid        NOT NULL DEFAULT gen_random_uuid(),
    lease_expires_at timestamptz NULL,
    upstream_ref     text        NULL,              -- Magento entity id / increment id
    result           jsonb       NULL,              -- replayable response, set on success
    error_code       text        NULL,
    reconcile_after  timestamptz NULL,
    reconcile_count  integer     NOT NULL DEFAULT 0,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    finished_at      timestamptz NULL,
    CONSTRAINT operations_idem_uq UNIQUE (instance_id, operation, idempotency_key),
    CONSTRAINT operations_money_chk CHECK (
        (amount_minor IS NULL) = (currency IS NULL)
        AND (amount_minor IS NULL OR currency ~ '^[A-Z]{3}$')),
    -- Terminal means finished, and finished means terminal. A row in pending,
    -- executing, unknown or reconciling can never carry a finished_at.
    CONSTRAINT operations_terminal_chk CHECK (
        (state IN ('succeeded','failed')) = (finished_at IS NOT NULL)),
    CONSTRAINT operations_hash_len CHECK (
        octet_length(subject_hash) = 32 AND octet_length(args_hash) = 32),
    -- Only a claimed row may hold a lease, and a lease always belongs to a fence.
    CONSTRAINT operations_lease_chk CHECK (
        (lease_expires_at IS NULL) OR state IN ('executing','reconciling')),
    CONSTRAINT operations_key_len CHECK (length(idempotency_key) BETWEEN 1 AND 256),
    CONSTRAINT operations_entity_len CHECK (length(entity_id) BETWEEN 1 AND 256)
);

-- The reconciler's work queue: only rows that are due.
CREATE INDEX IF NOT EXISTS operations_unknown_idx
    ON operations (reconcile_after, id) WHERE state = 'unknown';
-- Detecting an abandoned executing row (its worker died mid-call).
CREATE INDEX IF NOT EXISTS operations_executing_idx
    ON operations (lease_expires_at) WHERE state = 'executing';
CREATE INDEX IF NOT EXISTS operations_entity_idx
    ON operations (instance_id, entity_type, entity_id, created_at DESC);
CREATE INDEX IF NOT EXISTS operations_subject_idx
    ON operations (instance_id, subject_hash, created_at DESC);
-- "what did this instance do to this order" and "what is unresolved".
CREATE INDEX IF NOT EXISTS operations_state_idx
    ON operations (instance_id, state, created_at DESC);

-- Append-only history: every transition, with the fence that caused it. This is
-- the audit trail a reconciliation or a dispute is argued from.
CREATE TABLE IF NOT EXISTS operation_transitions (
    seq          bigint      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    operation_id uuid        NOT NULL REFERENCES operations(id) ON DELETE RESTRICT,
    from_state   text        NOT NULL,             -- 'none' for the creating transition
    to_state     text        NOT NULL,
    fence        uuid        NOT NULL,
    attempt      integer     NOT NULL,
    reason       text        NOT NULL,
    occurred_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS operation_transitions_op_idx
    ON operation_transitions (operation_id, seq);